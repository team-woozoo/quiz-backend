package com.woozoo.quiz.concept.domain;

// 자료 안에 이 개념으로 어떤 유형의 문제를 낼 재료가 실제로 있는지 나타낸다. 업로드할 때 자료를 분석해 붙인다.
// 인지 유형 이름을 쓰지 않는 것은, 분석 모델이 "이 유형의 문제를 낼 수 있나"가 아니라 "자료에 이것이 적혀 있나"를 판단하게 하려는 것이다.
// 상수 이름이 응답 스키마의 허용 값이 되므로 분석 프롬프트(prompts/material-analysis-system.md)의 이름과 같아야 한다
public enum ConceptTag {
    // 비슷하지만 다른 개념의 짝 (이해: 비교하기)
    CONTRAST,
    // 개념이 성립하는 조건이나 범위 (이해: 분류하기)
    CONDITION,
    // 결과를 정하는 규칙, 공식, 절차, 코드의 동작 (적용)
    RULE,
    // 여러 요인이 함께 작용해 하나의 결과를 만든다는 설명 (분석)
    FACTORS,
    // 장단점이 서로 다른 대안들 (평가)
    TRADEOFF
}
